//! Character classification close to what Java's `Character` reports. The
//! standard library has no general-category lookup, so the categories Lucene
//! cares about (marks, punctuation, symbols, letter numbers) are approximated
//! with range tables over the commonly used blocks.

fn in_ranges(c: char, table: &[(u32, u32)]) -> bool {
    let v = c as u32;
    // Tables are sorted; a binary search keeps this cheap.
    let mut lo = 0usize;
    let mut hi = table.len();
    while lo < hi {
        let mid = (lo + hi) / 2;
        let (a, b) = table[mid];
        if v < a {
            hi = mid;
        } else if v > b {
            lo = mid + 1;
        } else {
            return true;
        }
    }
    false
}

