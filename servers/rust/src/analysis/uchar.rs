pub fn is_mark(c: char) -> bool {
    (c as u32) >= 0x300 && in_ranges(c, MARKS)
}

pub fn is_punct(c: char) -> bool {
    in_ranges(c, PUNCT)
}

pub fn is_symbol(c: char) -> bool {
    in_ranges(c, SYMBOLS)
}

/// Java `Character.isLetter`.
pub fn is_letter(c: char) -> bool {
    if c.is_ascii() {
        return c.is_ascii_alphabetic();
    }
    c.is_alphabetic() && !is_mark(c) && !in_ranges(c, LETTER_NUMBERS)
}

/// Java `Character.isDigit` (general category Nd).
pub fn is_digit(c: char) -> bool {
    if c.is_ascii() {
        return c.is_ascii_digit();
    }
    c.is_numeric() && !in_ranges(c, NON_DECIMAL_NUMBERS) && !in_ranges(c, LETTER_NUMBERS)
}

pub fn is_letter_or_digit(c: char) -> bool {
    is_letter(c) || is_digit(c)
}

/// Java `Character.isWhitespace`.
pub fn is_java_whitespace(c: char) -> bool {
    match c {
        '\t' | '\n' | '\u{0B}' | '\u{0C}' | '\r' | '\u{1C}'..='\u{1F}' | ' ' => true,
        '\u{A0}' | '\u{2007}' | '\u{202F}' => false,
        '\u{1680}' | '\u{2000}'..='\u{200A}' | '\u{2028}' | '\u{2029}' | '\u{205F}' | '\u{3000}' => true,
        _ => false,
    }
}

/// Unicode space separators, line and paragraph separators (Java SPACE_SEPARATOR etc.).
pub fn is_space_separator(c: char) -> bool {
    matches!(c, ' ' | '\u{A0}' | '\u{1680}' | '\u{2000}'..='\u{200A}' | '\u{202F}' | '\u{205F}' | '\u{3000}')
}

/// Java `Character.toLowerCase(int)`: a single code point mapping.
pub fn lower_char(c: char) -> char {
    if c.is_ascii() {
        return c.to_ascii_lowercase();
    }
    let mut it = c.to_lowercase();
    let first = it.next().unwrap_or(c);
    first
}

/// Java `Character.toUpperCase(int)`: characters without a single-code-point
/// uppercase form (ß, ligatures) stay as they are.
pub fn upper_char(c: char) -> char {
    if c.is_ascii() {
        return c.to_ascii_uppercase();
    }
    let mut it = c.to_uppercase();
    let first = it.next().unwrap_or(c);
    if it.next().is_some() {
        return c;
    }
    first
}

pub fn lower_str(s: &str) -> String {
    s.chars().map(lower_char).collect()
}

pub fn upper_str(s: &str) -> String {
    s.chars().map(upper_char).collect()
}

/// Number of UTF-16 code units of a string; Lucene offsets and lengths are
/// counted in Java chars.
pub fn utf16_len(s: &str) -> usize {
    s.chars().map(|c| c.len_utf16()).sum()
}

