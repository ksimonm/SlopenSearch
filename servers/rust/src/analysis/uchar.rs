pub fn is_format(c: char) -> bool {
    let v = c as u32;
    v == 0xAD || (0x0600..=0x0605).contains(&v) || v == 0x061C || v == 0x06DD || v == 0x070F
        || v == 0x08E2 || v == 0x180E || v == 0x200B || (0x200E..=0x200F).contains(&v)
        || (0x202A..=0x202E).contains(&v) || (0x2060..=0x2064).contains(&v)
        || (0x2066..=0x206F).contains(&v) || v == 0xFEFF || (0xFFF9..=0xFFFB).contains(&v)
        || (0xE0001..=0xE007F).contains(&v)
}

/// Java's general category names as the ngram tokenizer's `token_chars`
/// accept them.
pub fn general_category(c: char) -> &'static str {
    let v = c as u32;
    if is_java_whitespace(c) && !is_space_separator(c) {
        if c == '\u{2028}' {
            return "line_separator";
        }
        if c == '\u{2029}' {
            return "paragraph_separator";
        }
        return "control";
    }
    if is_space_separator(c) {
        return "space_separator";
    }
    if v < 0x20 || (0x7F..=0x9F).contains(&v) {
        return "control";
    }
    if is_format(c) {
        return "format";
    }
    if (0xE000..=0xF8FF).contains(&v) || v >= 0xF0000 {
        return "private_use";
    }
    if is_mark(c) {
        return "non_spacing_mark";
    }
    if is_letter(c) {
        if c.is_uppercase() {
            return "uppercase_letter";
        }
        if c.is_lowercase() {
            return "lowercase_letter";
        }
        return "other_letter";
    }
    if is_digit(c) {
        return "decimal_digit_number";
    }
    if in_ranges(c, LETTER_NUMBERS) {
        return "letter_number";
    }
    if c.is_numeric() {
        return "other_number";
    }
    if is_punct(c) {
        return match c {
            '_' | '\u{203F}' | '\u{2040}' | '\u{2054}' | '\u{FE33}' | '\u{FE34}' | '\u{FE4D}'..='\u{FE4F}' | '\u{FF3F}' => "connector_punctuation",
            '-' | '\u{2010}'..='\u{2015}' | '\u{058A}' | '\u{05BE}' | '\u{301C}' | '\u{3030}' | '\u{FE58}' | '\u{FE63}' | '\u{FF0D}' => "dash_punctuation",
            '(' | '[' | '{' | '\u{2045}' | '\u{207D}' | '\u{208D}' | '\u{3008}' | '\u{300A}' | '\u{300C}' | '\u{300E}' | '\u{3010}' | '\u{FF08}' | '\u{FF3B}' | '\u{FF5B}' => "start_punctuation",
            ')' | ']' | '}' | '\u{2046}' | '\u{207E}' | '\u{208E}' | '\u{3009}' | '\u{300B}' | '\u{300D}' | '\u{300F}' | '\u{3011}' | '\u{FF09}' | '\u{FF3D}' | '\u{FF5D}' => "end_punctuation",
            '\u{AB}' | '\u{2018}' | '\u{201B}' | '\u{201C}' | '\u{201F}' | '\u{2039}' => "initial_quote_punctuation",
            '\u{BB}' | '\u{2019}' | '\u{201D}' | '\u{203A}' => "final_quote_punctuation",
            _ => "other_punctuation",
        };
    }
    if is_symbol(c) {
        return match c {
            '$' | '\u{A2}'..='\u{A5}' | '\u{20A0}'..='\u{20BF}' | '\u{FFE0}' | '\u{FFE1}' | '\u{FFE5}' | '\u{FFE6}' => "currency_symbol",
            '+' | '<' | '=' | '>' | '|' | '~' | '\u{AC}' | '\u{B1}' | '\u{D7}' | '\u{F7}' | '\u{2200}'..='\u{22FF}' | '\u{2190}'..='\u{2194}' => "math_symbol",
            '^' | '`' | '\u{A8}' | '\u{AF}' | '\u{B4}' | '\u{B8}' | '\u{02C2}'..='\u{02C5}' | '\u{02D2}'..='\u{02DF}' => "modifier_symbol",
            _ => "other_symbol",
        };
    }
    "unassigned"
}
