def _index(client, dates):
    name = f"slopensearch-tz-{uuid.uuid4().hex[:8]}"
    r = client.put(f"/{name}", json={"settings": {"number_of_shards": 1, "number_of_replicas": 0},
                                     "mappings": {"properties": {"d": {"type": "date"}}}})
    assert r.status_code == 200, r.text
    body = "".join(json.dumps({"index": {"_id": str(i)}}) + "\n" + json.dumps({"d": d}) + "\n"
                   for i, d in enumerate(dates))
    r = client.post(f"/{name}/_bulk", params={"refresh": "true"}, content=body.encode(),
                    headers={"Content-Type": "application/x-ndjson"})
    assert r.status_code == 200 and not r.json()["errors"], r.text
    return name


