def _painless(client, source, params):
    r = client.post("/_scripts/painless/_execute", json={"script": {"source": source, "params": params}})
    if r.status_code != 200:
        cause = r.json()["error"]["caused_by"]
        return ("error", cause["type"], cause["reason"])
    return r.json()["result"]


